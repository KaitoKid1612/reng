import { randomBytes } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { parseArgs } from "node:util";

import { z } from "zod";

import { importDailySheet } from "../lib/daily-sheet-import";
import { findPublishProblems, toPublishableContent } from "../lib/lesson-draft";

// Turns the teacher's daily Google Sheet export ({ today, history, keys } rows) into the
// question-bank lesson, adds it to a class, assigns today's exact set and sets the daily size.
// Without --out it only validates. The SQL calls the same database functions as the app and
// runs as one statement, so either everything is created or nothing is:
//   npm run daily:import -- --source sheet.json --teacher-id <uuid> --class-id <uuid> --out import.sql
//   npx supabase db query --linked --file import.sql
const sourceSchema = z.object({
  today: z.array(z.array(z.unknown())),
  history: z.array(z.array(z.unknown())),
  keys: z.array(z.array(z.unknown())),
});

// Dollar quoting with a random tag keeps any lesson text literal inside the SQL.
function quote(value: string) {
  const tag = `$q${randomBytes(6).toString("hex")}$`;
  if (value.includes(tag)) {
    throw new Error("Unable to quote the lesson content.");
  }
  return `${tag}${value}${tag}`;
}

async function main() {
  const { values } = parseArgs({
    options: {
      source: { type: "string" },
      "teacher-id": { type: "string" },
      "class-id": { type: "string" },
      "daily-size": { type: "string", default: "60" },
      out: { type: "string" },
    },
  });
  const teacherId = z.uuid().parse(values["teacher-id"]);
  const classId = z.uuid().parse(values["class-id"]);
  const dailySize = z.coerce.number().int().min(3).max(60).parse(values["daily-size"]);
  if (!values.source) {
    throw new Error("Provide --source with the exported sheet rows.");
  }
  const source = sourceSchema.parse(JSON.parse(await readFile(values.source, "utf8")));
  const { date, dueAt, todayIds, draft } = importDailySheet(source);
  const state = {
    metadata: {
      title: draft.title,
      titleJa: draft.titleJa,
      summary: draft.summary,
      order: draft.order,
      courseId: draft.courseId,
    },
    content: draft.content,
  };
  const problems = findPublishProblems(state);
  if (problems.length) {
    throw new Error(
      `The bank cannot be published: ${problems.map((item) => item.message).join(" ")}`,
    );
  }
  const content = toPublishableContent(state.content);
  const kinds = new Map<string, number>();
  for (const question of content.questions.filter((item) => todayIds.includes(item.id))) {
    const kind = question.tags[0] ?? "";
    kinds.set(kind, (kinds.get(kind) ?? 0) + 1);
  }
  console.log(
    `Validated ${date}: bank of ${content.questions.length} questions, today ${todayIds.length} (${[...kinds].map(([kind, count]) => `${kind} ${count}`).join(", ")}), due ${dueAt}.`,
  );
  if (!values.out) {
    console.log("Dry-run: no SQL written.");
    return;
  }
  const [day, month] = [date.slice(8, 10), date.slice(5, 7)];
  const title = `Bài hôm nay ${day}/${month} — ôn N5 (${todayIds.length} câu)`;
  const sql = `-- Generated by scripts/import-daily-sheet.ts for ${date}. Review, then run:
--   npx supabase db query --linked --file <this file>
do $import$
declare
  v_version uuid;
  v_order integer;
  v_pass_score integer;
begin
  if exists (select 1 from public.lessons where id = ${quote(draft.id)}) then
    raise exception 'reng:bank_exists';
  end if;
  v_version := public.publish_lesson(${quote(draft.id)}, ${quote(teacherId)}::uuid, 0,
    ${quote(draft.title)}, ${quote(draft.titleJa)}, ${quote(draft.summary)}, ${draft.order},
    ${quote(draft.courseId)}, ${quote(JSON.stringify(content))}::jsonb);
  select coalesce(max(order_no), 0) + 1 into v_order from public.class_lessons
    where class_id = ${quote(classId)}::uuid;
  perform public.upsert_class_lesson(${quote(teacherId)}::uuid, ${quote(classId)}::uuid,
    ${quote(draft.id)}, v_version, v_order, now());
  select pass_score into v_pass_score from public.classes where id = ${quote(classId)}::uuid;
  -- Same settings as the automatic daily practice: practice mode, late work allowed, 3 attempts.
  perform public.publish_assignment(${quote(teacherId)}::uuid, ${quote(classId)}::uuid,
    ${quote(draft.id)}, ${quote(title)}, 'practice', ${quote(dueAt)}::timestamptz, true,
    v_pass_score, 3, 'after_submit', array[${todayIds.map(quote).join(", ")}]::text[], null);
  perform public.set_daily_practice(${quote(teacherId)}::uuid, ${quote(classId)}::uuid, ${dailySize});
end
$import$;
`;
  await writeFile(values.out, sql, { mode: 0o600 });
  console.log(`Wrote ${values.out}. Review it, then run it with the linked Supabase CLI.`);
}

main().catch((error: unknown) => {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
});
